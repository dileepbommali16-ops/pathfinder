"""
Voice agent auxiliary routes: file upload endpoint + resume generation data tool.
Mounted under /api via backend/api.py; re-exported from agent/router.py so Gemini Live
learns of generate_resume during streaming turns.
"""
import os
import time
import logging
from typing import Any, Dict, Optional

from fastapi import APIRouter, File, HTTPException, Request, UploadFile
from pydantic import BaseModel

logger = logging.getLogger("agent.routes.voice")

router = APIRouter(prefix="/api", tags=["voice"])

MAX_UPLOAD_BYTES = 10 * 1024 * 1024  # 10MB cap (plaintext resumes / text are small)

UPLOAD_FILES: Dict[str, Dict[str, Any]] = {}
RESUME_STATUS: Dict[str, Dict[str, Any]] = {}


class UploadAck(BaseModel):
    id: str
    filename: str
    bytes_size: int
    mime_type: str


@router.post("/voice/upload")
async def upload_file(request: Request, file: UploadFile = File(...)):
    """Accepts a single file up to 10MB, stores metadata in-memory, returns an id."""
    content = await file.read()
    if len(content) > MAX_UPLOAD_BYTES:
        raise HTTPException(413, "File too large. Use a smaller PDF/DOCX or paste text instead.")

    fid = f"file_{len(UPLOAD_FILES) + 1}_{int(os.getpid())}"
    UPLOAD_FILES[fid] = {
        "filename": file.filename or "untitled",
        "data": content,
        "mime": file.content_type or "application/octet-stream",
        "bytes_size": len(content),
        "accepted_at": time.time(),
    }
    return {"success": True, "data": {"id": fid, **UPLOAD_FILES[fid]}}


@router.post("/voice/upload/check")
async def check_files():
    """Returns currently held upload ids (for client polling after an upload)."""
    return {"success": True, "data": list(UPLOAD_FILES.keys())}


class GenerateResumeReq(BaseModel):
    profile_fields: Dict[str, Any] = {}


@router.post("/ai/generate-resume")
async def generate_resume(req: GenerateResumeReq, request: Request):
    """Generates a one-page ATS resume markdown from profile fields. Returns feedback + a download link."""
    if not req.profile_fields:
        raise HTTPException(400, "Profile fields required to generate resume.")

    p = dict(req.profile_fields)
    branch = str(p.get("branch") or p.get("branchCode") or "CSE").upper().strip()
    cgpa = str(p.get("cgpa") or "")
    backlogs = str(p.get("backlogs") or p.get("activeBacklogs") or "")
    internships = str(p.get("internships") or 0)
    coding = str(p.get("coding") or "")
    communication = str(p.get("communication") or "")
    role = str(p.get("target_role") or p.get("targetRole") or "Software Development Engineer").strip()
    year = str(p.get("graduation_year") or p.get("graduationYear") or "")
    skills = [k for k, v in dict(p).items() if isinstance(v, str) and v.strip()]

    lines = [
        f"# {role}",
        "",
        f"- **Name**: Candidate (your school / campus)",
        f"- **Branch**: {branch}",
        f"- **CGPA**: {cgpa if cgpa else '—'}",
        f"- **Backlogs**: {backlogs if backlogs else 'None'}",
        f"- **Internships**: {internships}",
        f"- **Graduation Year**: {year}",
        "",
        "## Technical Skills",
        "",
        "\n".join(f"- {s}" for s in skills[:15]) or "—",
        "",
        "## Projects",
        "",
        "| Project | Domain | Difficulty |",
        "|---|---|---|",
        "| Distributed RAG pipeline | Cloud / RAG | Medium |",
        "| WebSocket real-time coach | Full-Stack | Hard |",
        "",
        "## Readiness Score",
        "",
        f"- Coding confidence: {coding or '—'}",
        f"- Communication rating: {communication or '—'}",
        "",
        "Generated by Pathfinder AI Career Coach.",
    ]
    md = "\n".join(lines)
    feedback = {
        "score": round((float(cgpa) if cgpa else 7.8)),
        "verdict": "ATS-optimized one-page resume generated from your profile. Upload it for live ATS scoring.",
        "strengths": ["Clean single-column layout", "Matched target role for keyword density"],
        "improvements": ["Add quantified project bullets (X days, Y% improvement)", "Add links to GitHub repos"],
        "ats_keywords": ["REST APIs", "Data Structures", "Docker", "Unit Testing"],
        "formatting_tips": ["Keep under 2MB selectable text", "Match ATS taxonomy"],
    }
    result = {"markdown": md, "feedback": feedback, "download_url": "/api/ai/resume-download?format=text"}
    RESUME_STATUS["last"] = result
    return {"success": True, "data": result}


@router.get("/ai/resume-download")
async def download_resume():
    return RESUME_STATUS.get("last", {}).get("download_url") or ""
